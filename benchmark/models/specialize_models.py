#!/usr/bin/env python3
"""
Generate static ONNX model variants for SOFIE GPU benchmarking.

Most source models are parametric ONNX models with dynamic input dimensions.
For those models, concrete input shapes are assigned and ONNX shape inference
is used to propagate the static dimensions through the graph.

MAMBAV2.onnx is different: it is already specialized to sequence length 512,
with the sequence dimension embedded in internal reshape tensors. Its variants
are therefore generated by explicitly replacing those sequence dimensions.

Usage:
    python3 specialize_models.py
"""

import copy
import os

import numpy as np
import onnx
from onnx import numpy_helper, shape_inference


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

BASE = os.path.dirname(os.path.abspath(__file__))


def set_static_inputs(model: onnx.ModelProto,
                      shape_map: dict[str, list[int]]) -> onnx.ModelProto:
    """Return a copy of model with graph inputs specialized to static shapes."""
    m = copy.deepcopy(model)

    for inp in m.graph.input:
        if inp.name not in shape_map:
            continue

        tensor_type = inp.type.tensor_type
        new_dims = shape_map[inp.name]

        if len(new_dims) != len(tensor_type.shape.dim):
            raise ValueError(
                f"{inp.name}: expected rank {len(tensor_type.shape.dim)}, "
                f"got {len(new_dims)}"
            )

        for i, dim in enumerate(tensor_type.shape.dim):
            dim.ClearField("dim_param")
            dim.dim_value = new_dims[i]

    return m


def fix_output_shapes(model: onnx.ModelProto) -> onnx.ModelProto:
    """Run ONNX shape inference to propagate concrete tensor dimensions."""
    return shape_inference.infer_shapes(
        model,
        check_type=True,
        strict_mode=False,
        data_prop=True,
    )


def verify_no_dynamic_shapes(model: onnx.ModelProto, name: str) -> None:
    """Report any remaining dynamic dimensions in graph tensor metadata."""
    dynamic = []

    values = (
            list(model.graph.input)
            + list(model.graph.output)
            + list(model.graph.value_info)
    )

    for value in values:
        if not value.type.HasField("tensor_type"):
            continue

        dims = value.type.tensor_type.shape.dim
        unresolved = [
            dim.dim_param if dim.dim_param else "?"
            for dim in dims
            if dim.dim_param or not dim.HasField("dim_value")
        ]

        if unresolved:
            dynamic.append((value.name, unresolved))

    if dynamic:
        print(f"  [WARN] {name}: {len(dynamic)} tensors still have dynamic dimensions")
        for tensor_name, dims in dynamic[:10]:
            print(f"         {tensor_name}: {dims}")
    else:
        print(f"  [OK] {name}: all inferred tensor shapes are static")


def patch_output_shapes(model: onnx.ModelProto,
                        output_shape_map: dict[str, list[int | str]]) -> onnx.ModelProto:
    """
    Set output shapes explicitly where ONNX shape inference cannot resolve them.

    Integer entries are written as concrete dimensions. String entries are left
    unchanged.
    """
    m = copy.deepcopy(model)

    for out in m.graph.output:
        if out.name not in output_shape_map:
            continue

        tensor_type = out.type.tensor_type
        new_dims = output_shape_map[out.name]

        for i, dim in enumerate(tensor_type.shape.dim):
            value = new_dims[i]

            if isinstance(value, int):
                dim.ClearField("dim_param")
                dim.dim_value = value

    return m


def save(model: onnx.ModelProto, path: str) -> None:
    onnx.checker.check_model(model)
    onnx.save(model, path)

    size_kb = os.path.getsize(path) / 1024
    print(f"  -> saved {os.path.basename(path)} ({size_kb:.0f} KB)")


