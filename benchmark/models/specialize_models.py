# Generic dynamic-model specialization
# ---------------------------------------------------------------------------

def specialize_family(model_names: list[str],
                      variants: list[dict],
                      shape_map_fn,
                      suffix_fn,
                      output_shape_map_fn=None) -> None:
    for model_name in model_names:
        src_path = os.path.join(BASE, model_name)

        if not os.path.exists(src_path):
            print(f"[SKIP] {model_name} - file not found")
            continue

        stem = model_name.removesuffix(".onnx")

        # Load external data so generated variants contain the complete model.
        base_model = onnx.load(src_path, load_external_data=True)

        print(f"\nSpecializing {model_name}:")

        for variant in variants:
            out_name = f"{stem}_{suffix_fn(variant)}.onnx"
            out_path = os.path.join(BASE, out_name)

            shape_map = shape_map_fn(**variant)
            model = set_static_inputs(base_model, shape_map)

            try:
                model = fix_output_shapes(model)
            except Exception as e:
                print(f"  [WARN] shape inference failed for {out_name}: {e}")

            if output_shape_map_fn is not None:
                output_shape_map = output_shape_map_fn(**variant)
                model = patch_output_shapes(model, output_shape_map)

            verify_no_dynamic_shapes(model, out_name)
            save(model, out_path)


# ---------------------------------------------------------------------------
# MambaV2
# ---------------------------------------------------------------------------

MAMBAV2_SOURCE = "MAMBAV2.onnx"
MAMBAV2_ORIGINAL_LENGTH = 512

MAMBAV2_LENGTHS = [
    128,
    256,
    512,
    1024,
    2048,
]


def replace_mambav2_sequence_dimension(shape: list[int],
                                       sequence_length: int) -> list[int]:
    shape = list(shape)

    if len(shape) == 2 and shape[0] == MAMBAV2_ORIGINAL_LENGTH:
        shape[0] = sequence_length

    elif (
            len(shape) == 3
            and shape[0] == 1
            and shape[1] == MAMBAV2_ORIGINAL_LENGTH
    ):
        shape[1] = sequence_length

    return shape


def update_mambav2_value_info(value_info,
                              sequence_length: int) -> None:
    tensor_type = value_info.type.tensor_type

    if not tensor_type.HasField("shape"):
        return

    dims = tensor_type.shape.dim

    if (
            len(dims) == 2
            and dims[0].HasField("dim_value")
            and dims[0].dim_value == MAMBAV2_ORIGINAL_LENGTH
    ):
        dims[0].dim_value = sequence_length

    elif (
            len(dims) == 3
            and dims[0].HasField("dim_value")
            and dims[0].dim_value == 1
            and dims[1].HasField("dim_value")
            and dims[1].dim_value == MAMBAV2_ORIGINAL_LENGTH
    ):
        dims[1].dim_value = sequence_length


def specialize_mambav2() -> None:
    src_path = os.path.join(BASE, MAMBAV2_SOURCE)

    if not os.path.exists(src_path):
        print(f"[SKIP] {MAMBAV2_SOURCE} - file not found")
        return

    print(f"\nSpecializing {MAMBAV2_SOURCE}:")

    for sequence_length in MAMBAV2_LENGTHS:
        model = onnx.load(src_path, load_external_data=True)

        initializer_names = {
            initializer.name
            for initializer in model.graph.initializer
        }

        changed_shapes = 0

        # Some reshape shapes are stored directly as graph initializers.
        for initializer in model.graph.initializer:
            if not initializer.name.startswith("shape_"):
                continue

            value = numpy_helper.to_array(initializer)

            if not np.issubdtype(value.dtype, np.integer):
                continue

            old_shape = value.tolist()
            new_shape = replace_mambav2_sequence_dimension(
                old_shape,
                sequence_length,
            )

            if new_shape == old_shape:
                continue

            new_value = np.asarray(new_shape, dtype=value.dtype)

            initializer.CopyFrom(
                numpy_helper.from_array(
                    new_value,
                    name=initializer.name,
                )
            )

            changed_shapes += 1

        # Other reshape shapes may be produced by Constant nodes.
        for node in model.graph.node:
            if (
                    node.op_type != "Constant"
                    or not node.output
                    or not node.output[0].startswith("shape_")
            ):
                continue

            for attr in node.attribute:
                if attr.name != "value":
                    continue

                value = numpy_helper.to_array(attr.t)

                if not np.issubdtype(value.dtype, np.integer):
                    continue

                old_shape = value.tolist()
                new_shape = replace_mambav2_sequence_dimension(
                    old_shape,
                    sequence_length,
                )

                if new_shape == old_shape:
                    continue

                new_value = np.asarray(new_shape, dtype=value.dtype)
                attr.t.CopyFrom(numpy_helper.from_array(new_value))

                changed_shapes += 1

        # Update the sequence dimension recorded in graph tensor metadata.
        values = (
                list(model.graph.input)
                + list(model.graph.value_info)
                + list(model.graph.output)
        )

        for value_info in values:
            if value_info.name in initializer_names:
                continue

            update_mambav2_value_info(
                value_info,
                sequence_length,
            )

        expected_changes = (
            0
            if sequence_length == MAMBAV2_ORIGINAL_LENGTH
            else 42
        )

        if changed_shapes != expected_changes:
            raise RuntimeError(
                f"Expected to update {expected_changes} MambaV2 reshape "
                f"constants for L={sequence_length}, but updated "
                f"{changed_shapes}. Refusing to write a potentially "
                "inconsistent model."
            )

        out_name = f"mambav2_L{sequence_length}.onnx"
        out_path = os.path.join(BASE, out_name)

        save(model, out_path)


